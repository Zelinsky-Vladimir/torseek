#!/usr/bin/env node
// Regenerates category tables for hand-written indexers from Jackett's C# sources.
//   node scripts/gen-native-categories.mjs <path-to-Jackett-checkout>

import { readFileSync, writeFileSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const jackett = process.argv[2]
if (!jackett) throw new Error('usage: gen-native-categories.mjs <jackett checkout>')
const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const common = join(jackett, 'src/Jackett.Common')

// TorznabCatType.MoviesForeign -> "Movies/Foreign"
const catTypes = Object.fromEntries(
  [...readFileSync(join(common, 'Models/TorznabCatType.cs'), 'utf8').matchAll(/TorznabCategory (\w+) = new TorznabCategory\(\d+, "([^"]+)"\)/g)].map((m) => [m[1], m[2]]),
)

for (const [cls, out] of [
  ['RuTracker', 'rutracker-categories.ts'],
  ['Toloka', 'toloka-categories.ts'],
]) {
  const src = readFileSync(join(common, `Indexers/Definitions/${cls}.cs`), 'utf8')
  const rows = [...src.matchAll(/AddCategoryMapping\((\d+), TorznabCatType\.(\w+), "((?:[^"\\]|\\.)*)"\)/g)].map((m) => {
    const name = catTypes[m[2]]
    if (!name) throw new Error(`${cls}: unknown TorznabCatType.${m[2]}`)
    return `  [${m[1]}, '${name}', ${JSON.stringify(m[3].replace(/\\"/g, '"'))}],`
  })
  const body = `// Generated by scripts/gen-native-categories.mjs from Jackett's ${cls}.cs. Do not edit.\n// [tracker forum id, Torznab category, description]\nexport const CATEGORIES: [number, string, string][] = [\n${rows.join('\n')}\n]\n`
  writeFileSync(join(root, 'src/core/native', out), body)
  console.log(`${out}: ${rows.length} mappings`)
}
